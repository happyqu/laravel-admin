// Keep the upstream distribution unchanged; isolate calendar construction locally.
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const upstream = fs.readFileSync(path.join(root, 'resources/assets/flatpickr/dist/flatpickr.js'), 'utf8');

const compatibility = `(function (BrowserDate) {
    function CalendarDate(year, month, day, hours, minutes, seconds, milliseconds) {
        if (!arguments.length) return new BrowserDate();
        if (arguments.length === 1) return new BrowserDate(year);
        // Local setters avoid extra offsets applied to multi-argument constructors.
        // Preserve local timezone/DST rules, year 0-99 handling and overflow.
        var date = new BrowserDate(0);
        var integerYear = Number(year) < 0 ? Math.ceil(Number(year)) : Math.floor(Number(year));
        date.setHours(0, 0, 0, 0);
        date.setFullYear(integerYear >= 0 && integerYear <= 99 ? 1900 + integerYear : Number(year), month,
            arguments.length > 2 ? day : 1);
        date.setHours(arguments.length > 3 ? hours : 0, arguments.length > 4 ? minutes : 0,
            arguments.length > 5 ? seconds : 0, arguments.length > 6 ? milliseconds : 0);
        return date;
    }
    CalendarDate.prototype = BrowserDate.prototype;
    CalendarDate.now = function () { return BrowserDate.now(); };
    CalendarDate.parse = function (value) { return BrowserDate.parse(value); };
    CalendarDate.UTC = BrowserDate.UTC;
    return CalendarDate;
})(Date)`;

const output = '/* Generated by tools/build-flatpickr.cjs. Do not edit. Upstream flatpickr: MIT. */\n'
    + '(function (Date) {\n' + upstream + '\n}).call(this, ' + compatibility + ');\n';
const target = path.join(root, 'resources/assets/laravel-admin/flatpickr-local.js');
if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) {
        throw new Error('Run node tools/build-flatpickr.cjs to regenerate flatpickr-local.js');
    }
} else {
    fs.writeFileSync(target, output);
}
