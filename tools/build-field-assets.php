<?php

require __DIR__.'/../vendor/autoload.php';

$fields = \Encore\Admin\Form::$availableFields;
$assets = [];

foreach ($fields as $class) {
    if (!is_string($class) || !class_exists($class) || !method_exists($class, 'getAssets')) {
        continue;
    }

    $definition = $class::getAssets();
    $assets[$class] = [
        'css' => array_values(array_filter((array) ($definition['css'] ?? []))),
        'js' => array_values(array_filter((array) ($definition['js'] ?? []))),
    ];
}

ksort($assets);

$output = "<?php\n\n"
    ."// Generated by tools/build-field-assets.php. Rebuild after changing built-in field assets.\n"
    ."return ".var_export($assets, true).";\n";

if (file_put_contents(__DIR__.'/../resources/field-assets.php', $output) === false) {
    fwrite(STDERR, "Unable to write resources/field-assets.php\n");
    exit(1);
}

echo 'Generated '.count($assets)." field asset definitions.\n";
