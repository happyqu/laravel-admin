<?php

namespace Encore\Admin\Concerns;

use Encore\Admin\Admin;
use Encore\Admin\IframeTabs\IframeTabs;
use Illuminate\Support\Arr;

trait RegistersIframeTabs
{
    /**
     * Register any application services.
     *
     * @return void
     */
    protected function registerIframeTabs()
    {
        Admin::booted(function () {
            if (IframeTabs::boot() && $this->inWeb()) {
                IframeTabs::fixMinify();
            }
        });
    }

    protected function inWeb()
    {
        if (IframeTabs::config('web_in_cli', false)) {
            return true;
        }

        $c = request('c', '');

        return !$this->app->runningInConsole()
            && (!$c || !preg_match('/.*?admin:minify.*?/i', $c));
    }

    /**
     * {@inheritdoc}
     */
    protected function bootIframeTabs()
    {
        if (!IframeTabs::boot()) {
            return;
        }

        if (!$this->app->routesAreCached()) {
            $this->app->booted(function () {
                IframeTabs::routes(__DIR__.'/../../routes/iframe-tabs.php');
            });
        }

        $layerPath = IframeTabs::config('layer_path', 'vendor/laravel-admin/iframe-tabs/layer/layer.js');

        if (!file_exists(public_path($layerPath))) {
            $layerPath = '';
        }

        Admin::booting(function () use ($layerPath) {
            Admin::js('vendor/laravel-admin/iframe-tabs/bootstrap-tab.js');

            if ($layerPath) {
                Admin::js($layerPath);
            }
        });

        if (!$this->inWeb()) {
            return;
        }

        Admin::booted(function () use ($layerPath) {
            if (IframeTabs::isMinify() && $layerPath) {
                Admin::css(preg_replace('/^(.+)layer\.js.*$/i', '$1theme/default/layer.css?v=iframe-tabs', $layerPath));
            }

            if (\Request::route() && \Request::route()->getName() === 'iframes.index') {
                $this->useAdminViews('index');

                Admin::css(IframeTabs::config('tabs_css', 'vendor/laravel-admin/iframe-tabs/dashboard.css'));

                $layout = config('admin.layout', ['layout-fixed']);
                if (count($layout) == 1) {
                    $layout = explode(' ', $layout[0]);
                }
                if (count($layout) && !in_array('layout-fixed', $layout)) {
                    $layout[] = 'layout-fixed';
                    config(['admin.layout' => $layout]);
                }
            } else {
                $this->initSubPage();
                $this->useAdminViews('content');
                $this->contentScript();

                Admin::css('vendor/laravel-admin/iframe-tabs/content.css');

                config(['admin.layout' => ['layout-fixed']]);
            }

            config(['admin.minify_assets.enabled' => false]);
        });
    }

    protected function useAdminViews($mode)
    {
        $finder = app('view')->getFinder();
        $overrides = [__DIR__.'/../../resources/views/iframe-tabs/index', __DIR__.'/../../resources/views/iframe-tabs/content'];
        $paths = array_values(array_diff($finder->getHints()['admin'] ?? [], $overrides));
        $finder->replaceNamespace('admin', array_merge([__DIR__.'/../../resources/views/iframe-tabs/'.$mode], $paths));
        $finder->flush();
    }

    protected function initSubPage()
    {
        if (!in_array(IframeTabs::config('bind_urls', 'none'), ['new_tab', 'popup'])) {
            return;
        }

        $method = strtolower(request()->method());
        $session = request()->session();

        if ($method === 'get') {
            $iframeId = (string) $session->pull('_iframe_id_', '');
            $afterSave = (string) $session->pull('after_save', '');

            if ($iframeId && $session->has('toastr')) {
                $toastr = admin_toastr_payload($session->get('toastr'));
                $type = $toastr['type'];
                $message = $toastr['message'];

                if ($type === 'success') {
                    $session->put('_list_iframe_id_', $iframeId);
                    $session->put('_list_after_save_', $afterSave);
                    $session->put('_success_message_', $message);
                }
            }

            return;
        }

        if ($method === 'put' || $method === 'post') {
            $iframeId = (string) request()->input('_iframe_id_', '');
            $afterSave = (string) request()->input('after-save', '');

            // The iframe id is generated by the tab container; keep it bounded and scalar.
            $iframeId = preg_match('/^[A-Za-z0-9_.:-]{0,128}$/', $iframeId) ? $iframeId : '';

            if ($iframeId !== '') {
                $session->put('_iframe_id_', $iframeId);
            } else {
                $session->forget('_iframe_id_');
            }

            if ($afterSave !== '') {
                $session->put('after_save', $afterSave);
            } else {
                $session->forget('after_save');
            }
        }
    }

    protected function contentScript()
    {
        $session = request()->session();

        $payload = [
            'iframeId' => (string) request()->input('_iframe_id_', ''),
            'listIframeId' => (string) $session->pull('_list_iframe_id_', ''),
            'listAfterSave' => (string) $session->pull('_list_after_save_', ''),
            'successMessage' => (string) $session->pull('_success_message_', 'success'),
            'layerSize' => (string) IframeTabs::config('layer_size', '1100px,98%'),
            'bindUrls' => (string) IframeTabs::config('bind_urls', 'popup'),
            'bindSelecter' => (string) IframeTabs::config('bind_selecter', ''),
            'homeUri' => admin_base_path('dashboard'),
        ];

        $json = json_encode(
            $payload,
            JSON_UNESCAPED_UNICODE | JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_INVALID_UTF8_SUBSTITUTE
        );

        $script = <<<'EOT'
(function () {
    'use strict';

    var data = __ADMIN_IFRAME_PAYLOAD__;
    var topWindow = window.top;

    function topDocument() {
        try {
            return topWindow.document;
        } catch (error) {
            return null;
        }
    }

    function reloadFrame(id) {
        if (!id) {
            return;
        }

        var doc = topDocument();
        if (!doc) {
            return;
        }

        var frame = doc.getElementById(id);
        if (frame && frame.contentWindow) {
            if (frame.contentWindow.$ && frame.contentWindow.$.admin && frame.contentWindow.$.admin.reload) {
                frame.contentWindow.$.admin.reload();
            } else {
                frame.contentWindow.location.reload();
            }
        }
    }

    function notify(message) {
        try {
            if (topWindow.toastr) {
                topWindow.toastr.success(message);
            }
        } catch (error) {
            // Cross-origin top window: ignore.
        }
    }

    function closeCurrentPopup() {
        try {
            parent.layer.close(parent.layer.getFrameIndex(window.name));
        } catch (error) {
            // No layer/popup context.
        }
    }

    function closeCurrentTab() {
        try {
            var frame = window.frameElement;
            if (frame && frame.id) {
                topWindow.closeTabByPageId(frame.id.replace(/^iframe_/i, ''));
            }
        } catch (error) {
            // No tab context.
        }
    }

    function isCurrentFrame(id) {
        var frame = window.frameElement;
        return !!frame && frame.id === id;
    }

    // A same-frame save already has its destination; only a separate editor
    // needs to refresh and return to its opener.
    if (data.listIframeId && !data.listAfterSave && !isCurrentFrame(data.listIframeId)) {
        reloadFrame(data.listIframeId);
        notify(data.successMessage);

        if (data.bindUrls === 'popup') {
            closeCurrentPopup();
        } else if (data.bindUrls === 'new_tab') {
            closeCurrentTab();
        }

        return;
    }

    $.admin.afterFormSaved = function (form, result) {
        var id = $(form).find('input[name="_iframe_id_"]').val();
        if (!id || isCurrentFrame(id) || result.after_save
            || (data.bindUrls !== 'popup' && data.bindUrls !== 'new_tab')) {
            return false;
        }
        var doc = topDocument();
        if (!doc || !doc.getElementById(id)) {
            return false;
        }
        reloadFrame(id);
        notify(result.message);
        if (data.bindUrls === 'popup') {
            closeCurrentPopup();
        } else {
            closeCurrentTab();
        }
        return true;
    };

    if (data.iframeId) {
        $('form').each(function () {
            if ($(this).find('input[name="_iframe_id_"]').length === 0) {
                $('<input>', {
                    type: 'hidden',
                    name: '_iframe_id_',
                    value: data.iframeId,
                }).appendTo(this);
            }
        });
    }

    $('body').off('.adminIframeContent').addClass('iframe-content');

    if ($('#terminal-box').length) {
        $(window).on('load', function () {
            var height = $('.content-wrapper').height() - 247;
            $('#terminal-box,.slimScrollDiv').css({ height: height + 'px' });
        });
    }

    $('body').on('click.adminIframeContent', '.breadcrumb li a', function () {
        var url = $(this).attr('href');
        if (url !== data.homeUri) {
            return;
        }

        try {
            topWindow.addTabs({
                id: '_admin_dashboard',
                title: topWindow.home_title,
                close: false,
                url: url,
                urlType: 'absolute',
                icon: '<i class="fa ' + topWindow.home_icon + '"></i>'
            });
        } catch (error) {
            window.location.href = url;
        }

        return false;
    });

    window.getCurrentId = function () {
        try {
            return window.frameElement && window.frameElement.id ? window.frameElement.id : '';
        } catch (error) {
            return '';
        }
    };

    window.doStop = function () {
        if (window.attachEvent && !window.opera) {
            document.execCommand('stop');
        } else {
            window.stop();
        }
    };

    window.openPop = function (url, title, area) {
        var layer = window.layer || topWindow.layer;
        if (!layer) {
            window.open(url, '_blank', 'noopener');
            return;
        }

        area = area || ['100%', '100%'];
        var index = layer.open({
            content: url,
            type: 2,
            title: title,
            anim: 2,
            closeBtn: 1,
            shade: false,
            area: area
        });

        window.Pops = window.Pops || [];
        window.Pops.push(index);

        return index;
    };

    window.closePop = function () {
        closeCurrentPopup();
    };

    window.closeTab = function () {
        closeCurrentTab();
        window.doStop();
    };

    if (data.bindUrls !== 'new_tab' && data.bindUrls !== 'popup') {
        return;
    }

    if (!data.bindSelecter) {
        return;
    }

    $('body').on('click.adminIframeContent', data.bindSelecter, function () {
        var url = $(this).attr('href');
        if (!url || url === '#' || /^javascript|\(|\)/i.test(url)) {
            return;
        }
        if ($(this).attr('target') === '_blank' || $(this).hasClass('iframes-pass-url')) {
            return;
        }

        var icon = $(this).find('i.fa').length ? $(this).find('i.fa').prop('outerHTML') : '<i class="fa fa-file-text"></i>';
        var title = ($(this).text() || $(this).attr('title') || '').trim();
        var tabId = window.getCurrentId();

        if (tabId) {
            url += (url.indexOf('?') > -1 ? '&' : '?') + '_iframe_id_=' + encodeURIComponent(tabId);
        }

        title = $('<div>').text(title).html();

        try {
            var tab = topWindow.findTabTitle(tabId.replace(/^iframe_(.+)$/, '$1'));
            if (tab) {
                title = ' ' + tab.text() + (title ? '-' + title : '');
            }
        } catch (error) {
            // No tab context.
        }

        if (data.bindUrls === 'popup') {
            var area = data.layerSize.split(',');
            var popw = $(this).attr('popw');
            var poph = $(this).attr('poph');
            if (popw && poph) {
                area = [popw, poph];
            }
            window.openPop(url, icon + title, area);
        } else {
            try {
                topWindow.openTab(url, title || '*', icon);
            } catch (error) {
                window.location.href = url;
            }
        }

        var toggle = $(this).parents('.grid-dropdown-actions').find('.dropdown-toggle');
        if (toggle.length) {
            toggle.trigger('click');
        }

        return false;
    });
})();
EOT;

        $script = str_replace('__ADMIN_IFRAME_PAYLOAD__', $json, $script);

        Admin::script($script);
    }
}
