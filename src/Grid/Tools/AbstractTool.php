<?php

namespace Encore\Admin\Grid\Tools;

use Encore\Admin\Grid;
use Encore\Admin\Widgets\Tool;

abstract class AbstractTool extends Tool
{
    /**
     * @var Grid
     */
    protected $grid;

    /**
     * @var bool
     */
    protected $disabled = false;

    /**
     * Toggle this button.
     *
     * @param bool $disable
     *
     * @return $this
     */
    public function disable(bool $disable = true)
    {
        $this->disabled = $disable;

        return $this;
    }

    /**
     * If the tool is allowed.
     */
    public function allowed()
    {
        return !$this->disabled;
    }

    /**
     * Set parent grid.
     *
     * @param Grid $grid
     *
     * @return $this
     */
    public function setGrid(Grid $grid)
    {
        $this->grid = $grid;

        return parent::setGrid($grid);
    }

    public function renderAuthorized()
    {
        return $this->allowed() ? parent::renderAuthorized() : '';
    }

    /**
     * @return Grid
     */
    public function getGrid()
    {
        return $this->grid;
    }

    /**
     * @return string
     */
    public function __toString()
    {
        return (string) $this->renderAuthorized();
    }
}
